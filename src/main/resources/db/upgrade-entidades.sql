    id UUID PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(255) NOT NULL,
    salud DOUBLE PRECISION NOT NULL,
    x DOUBLE PRECISION NOT NULL,
    y DOUBLE PRECISION NOT NULL,
    z DOUBLE PRECISION NOT NULL
);

